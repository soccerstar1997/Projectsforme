/*
 * 💬 نظرات مشتریان
 * ---------------------------------------------------------------------------
 * هیچ نظر، نام، امتیاز یا تعداد نظری ساخته نشده است. تا زمانی که نظرات واقعی
 * (با اجازهٔ صاحب نظر) ثبت نشوند، سایت یک حالت خالی صادقانه نشان می‌دهد.
 *
 * برای افزودن نظر واقعی، آیتم‌ها را در آرایهٔ زیر وارد کنید:
 *   { id, name, text, rating?, ratingVerified?, date?, verifiedVisit? }
 * امتیاز و برچسب «بازدید تأییدشده» فقط وقتی نمایش داده می‌شوند که مقدار
 * `ratingVerified` / `verifiedVisit` برابر true باشد — یعنی واقعاً بررسی شده باشد.
 */

export type Review = {
  id: string;
  name: string;
  text: string;
  /** امتیاز از ۵ */
  rating?: number;
  /** فقط اگر امتیاز واقعاً بررسی و تأیید شده باشد true شود */
  ratingVerified?: boolean;
  /** تاریخ نمایشی، مثل «آبان ۱۴۰۵» */
  date?: string;
  /** فقط اگر بازدید/سفارش مشتری واقعاً بررسی شده باشد true شود */
  verifiedVisit?: boolean;
};

export const reviews: Review[] = [];

